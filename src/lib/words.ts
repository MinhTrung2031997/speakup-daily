export type WordLevel = 'B1' | 'B2' | 'C1';
export type WordKind = 'phrasal' | 'idiom' | 'collocation' | 'word' | 'connector';

/** 17 catalogue slugs from src/lib/topics.ts, plus 'general' for connectors. */
export const TOPIC_SLUGS = [
  'tech', 'ai', 'work', 'remote', 'interviews', 'daily', 'food', 'health', 'money',
  'travel', 'vietnam', 'hobbies', 'social', 'opinions', 'whatif', 'smalltalk', 'stories',
] as const;
export type CatalogueSlug = (typeof TOPIC_SLUGS)[number];
export type TopicSlug = CatalogueSlug | 'general';
export const CONNECTOR_TOPIC: TopicSlug = 'general';

export interface WordEntry {
  phrase: string;
  /** Simple English, at most 12 words. */
  meaning: string;
  /** Short Vietnamese gloss. */
  vi: string;
  /** Natural spoken example (Hear it, sentence 1). */
  example: string;
  /** Second spoken example in a different context (Hear it, sentence 2). */
  example2: string;
  topic: TopicSlug;
  level: WordLevel;
  kind: WordKind;
  /** 2-3 common word pairs that go with the phrase. */
  collocations: string[];
  /** Typical wrong form, when useful (e.g. "do a decision"). Omit if none. */
  wrongPair?: string;
  /** Short personal question for the Use it step. */
  useItQuestion: string;
}

export interface WordPickerProfile {
  name?: string;
  job?: string;
  city?: string;
  level?: string;
  goals?: string;
  hobbies?: string;
}

// Copied from src/lib/learnPrompts.ts (this file has no imports).
export const LEVEL_RUBRIC = `Levels (pick one):
- "natural": meaning, grammar and collocation are all correct. Full review credit.
- "understandable": the meaning is right but the form or collocation is off (e.g. "bounce ideas with my team"). Half credit. Put the fixed sentence in "betterSentence".
- "off": wrong meaning or context, or the phrase was not used. One-line explanation in "feedback". Review next day.`;

const normPhrase = (s: string) =>
  (s || '').toLowerCase().replace(/[^a-z0-9 ]/g, ' ').replace(/\s+/g, ' ').trim();

function hashSeed(seed: string): number {
  let h = 2166136261;
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function mulberry32(a: number): () => number {
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle<T>(items: T[], rand: () => number): T[] {
  const a = items.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const tmp = a[i];
    a[i] = a[j]!;
    a[j] = tmp!;
  }
  return a;
}

/** Starting catalogue topic for a seed. A slug in the seed wins; else YYYY-MM-DD rotates; else a hash. */
export function topicIndexFromSeed(seed: string): number {
  const lower = (seed || '').toLowerCase();
  for (let i = 0; i < TOPIC_SLUGS.length; i++) {
    const slug = TOPIC_SLUGS[i];
    if (new RegExp('(?:^|\\b|:)' + slug + '(?:\\b|$)').test(lower)) return i;
  }
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(seed);
  if (m) {
    const day = Math.floor(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3])) / 86400000);
    return ((day % TOPIC_SLUGS.length) + TOPIC_SLUGS.length) % TOPIC_SLUGS.length;
  }
  return hashSeed(seed) % TOPIC_SLUGS.length;
}

export function dailyTopicSlug(seed: string): CatalogueSlug {
  return TOPIC_SLUGS[topicIndexFromSeed(seed)]!;
}

/**
 * Deterministic daily set: (n-1) unlearned words from today's/rotating topic
 * (then the next catalogue topics if that one is thin), plus 1 unlearned connector.
 * If connectors are exhausted, fill the last slot from the remaining bank.
 */
export function pickDailyWords(
  bank: WordEntry[],
  learnedPhrases: string[],
  seed: string,
  n = 5,
): WordEntry[] {
  const learned = new Set(learnedPhrases.map(normPhrase));
  const unused = bank.filter((w) => !learned.has(normPhrase(w.phrase)));
  const rand = mulberry32(hashSeed(seed || 'words'));
  const picked: WordEntry[] = [];
  const seen = new Set<string>();

  const take = (pool: WordEntry[], k: number) => {
    for (const w of shuffle(pool, rand)) {
      if (picked.length >= k) return;
      const key = normPhrase(w.phrase);
      if (!key || seen.has(key)) continue;
      seen.add(key);
      picked.push(w);
    }
  };

  const topicNeed = Math.max(0, n - 1);
  const start = topicIndexFromSeed(seed);
  for (let i = 0; i < TOPIC_SLUGS.length && picked.length < topicNeed; i++) {
    const slug = TOPIC_SLUGS[(start + i) % TOPIC_SLUGS.length];
    take(unused.filter((w) => w.topic === slug), topicNeed);
  }

  take(unused.filter((w) => w.topic === CONNECTOR_TOPIC), n);
  if (picked.length < n) take(unused, n);
  return picked;
}

function compactBank(bank: WordEntry[]): string {
  return bank.map((w) => `- ${w.phrase} [${w.topic}, ${w.level}, ${w.kind}] ${w.meaning}`).join('\n');
}

/** Extra Hear-it sentences + a typical Vietnamese-speaker slip. Bank examples are already on the entry. */
export function wordContextPrompt(words: Array<WordEntry | { phrase: string; meaning?: string; example?: string; example2?: string }>): string {
  const list = words.map((w) => ({
    phrase: w.phrase,
    meaning: 'meaning' in w ? w.meaning || '' : '',
    bankExamples: 'example' in w ? [w.example, 'example2' in w ? w.example2 : ''].filter(Boolean) : [],
  }));
  return `Target words: ${JSON.stringify(list)}

For EACH word, write 2 NEW short spoken example sentences in different everyday contexts (do NOT reuse the bank examples). Keep the phrase's words together exactly. Also name one common mistake Vietnamese speakers make with it (wrong preposition, do/make, a missing word, a literal translation, or a different meaning). One short line for the mistake.

JSON shape: {"items": [{"phrase": string, "examples": [string, string], "commonMistake": string}]}`;
}

/** Optional extra drill (not in the main 4 steps). New cloze sentence + 3 bank distractors. */
export function wordClozePrompt(word: WordEntry | string, distractors: string[] = []): string {
  const phrase = typeof word === 'string' ? word : word.phrase;
  const meaning = typeof word === 'string' ? '' : word.meaning;
  const source = typeof word === 'string' ? '' : [word.example, word.example2].join(' / ');
  const opts = distractors.length
    ? distractors.slice(0, 8)
    : WORD_BANK.filter((w) => normPhrase(w.phrase) !== normPhrase(phrase)).slice(0, 8).map((w) => w.phrase);
  return `Phrase: ${phrase}
Meaning: ${meaning || '(not given)'}
The bank sentences this phrase came from (do NOT reuse them): """${source}"""
Plausible distractors you may use (pick 3 that are clearly WRONG in your new sentence, not near-synonyms): ${JSON.stringify(opts)}

Write a NEW, short, everyday spoken sentence that uses the phrase WORD-FOR-WORD and fits the same meaning. Keep the phrase's words together exactly as written above. Then blank the phrase out with "____" and give 4 options: the correct phrase plus 3 plausible distractors (same kind of phrase, easy to confuse, not joke answers). Each distractor must be clearly WRONG or unnatural in this exact sentence, so only one option fits. Shuffle the options. "answer" is the 0-based index of the correct phrase in "options".

JSON shape: {"sentence": string, "blanked": string, "options": [string, string, string, string], "answer": number}`;
}

/** Optional end-of-session listen + retell. Discord-chat style, 60-80 words, uses all of today's words. */
export function wordStoryPrompt(words: Array<WordEntry | string>): string {
  const list = words.map((w) => (typeof w === 'string' ? { phrase: w } : { phrase: w.phrase, meaning: w.meaning }));
  return `Today's words (use ALL of them, naturally, no awkward stuffing): ${JSON.stringify(list)}

Write a short mini story OR a short Discord chat (two people, Alex and Sam, plus the learner Trung if it helps) that uses every phrase above. Aim for 60-80 words of spoken English. Casual tone, like friends on Discord. Do not explain the phrases. Keep each phrase's words together.

Return a flat "story" (one block, for a single TTS voice) and "lines" (turn-taking, for two-voice playback). "wordsUsed" must list every target phrase that actually appears, copied exactly.

JSON shape: {"title": string, "style": "chat"|"story", "story": string, "lines": [{"speaker": "Alex"|"Sam"|"Trung", "text": string}], "wordsUsed": [string]}`;
}

